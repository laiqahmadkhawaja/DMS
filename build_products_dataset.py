# Deduplicate by normalized name and supplier
unique_items = []
seen_keys = set()

counter = {"Hashim Enterprises": 1, "Kunafa Foods": 1, "Ujab Enterprises": 1}
prefixes = {
    "Hashim Enterprises": "HASH",
    "Kunafa Foods": "KUN",
    "Ujab Enterprises": "UJAB"
}

for item in raw_items:
    name_norm = re.sub(r'[\s\.\-_]+', ' ', item['name'].strip().lower())
    sup = item['supplier']
    key = (sup, name_norm)
    if key in seen_keys:
        continue
    seen_keys.add(key)
    
    code = f"{prefixes[sup]}-{counter[sup]:03d}"
    counter[sup] += 1
    
    # Calculate Wholesale / Distribution rate with slight margin or same as trade price
    # In FMCG distribution, company invoice rate is purchase rate (cost price),
    # wholesale rate to retailers is either standard trade price or marked up ~5-10% if purchase rate was net.
    p_rate = round(float(item['rate']), 2)
    w_rate = p_rate # default trade price from invoice
    r_rate = round(p_rate * 1.15, 2) # estimated retail MRP
    
    unique_items.append({
        "product_code": code,
        "product_name": item['name'].strip(),
        "supplier_name": sup,
        "category_name": item['category'],
        "packing_description": item['packing'],
        "carton_qty": item['carton_qty'],
        "pack_qty": item['pack_qty'],
        "unit": item['unit'],
        "purchase_rate": p_rate,
        "wholesale_rate": w_rate,
        "retail_rate": r_rate,
        "opening_stock": 0
    })

print(f"Total Unique Products Extracted: {len(unique_items)}")
for sup, cnt in counter.items():
    print(f" - {sup}: {cnt - 1} products")

